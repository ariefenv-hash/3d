import type { BoxDef, LevelDef } from './types';

const box = (p: [number, number, number], s: [number, number, number]): BoxDef => ({ p, s });
const hz = (p: [number, number, number], s: [number, number, number]): BoxDef => ({ p, s, hazard: true });

/** 封闭立方房间：内尺寸 w×h×d，中心在原点，墙厚 1，六面无缝 */
function room(w: number, h: number, d: number): BoxDef[] {
  const t = 1;
  const hw = w / 2, hh = h / 2, hd = d / 2;
  return [
    box([0, -(hh + t / 2), 0], [w + 2 * t, t, d + 2 * t]),
    box([0, hh + t / 2, 0], [w + 2 * t, t, d + 2 * t]),
    box([-(hw + t / 2), 0, 0], [t, h + 2 * t, d + 2 * t]),
    box([hw + t / 2, 0, 0], [t, h + 2 * t, d + 2 * t]),
    box([0, 0, -(hd + t / 2)], [w + 2 * t, h + 2 * t, t]),
    box([0, 0, hd + t / 2], [w + 2 * t, h + 2 * t, t]),
  ];
}

